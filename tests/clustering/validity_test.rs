fn to_array(rows: &[[f64; 2]]) -> Array2<f64> {
    Array2::from_shape_vec((rows.len(), 2), rows.iter().flatten().copied().collect()).unwrap()
}

#[test]
fn separated_clusters_match_the_reference() {
    let score = dbcv(&to_array(&SEPARATED), &SEPARATED_LABELS);
    assert!(
        (score - 0.8547950638740909).abs() < TOLERANCE,
        "score was {}",
        score
    );
}

/// Mutual reachability ties leave the spanning tree ambiguous, so overlapping clusters
/// are only pinned by sign and margin. The Python reference scores this case -0.124 off a
/// different tree through the same ties.
#[test]
fn overlapping_clusters_score_negative() {
    let score = dbcv(&to_array(&OVERLAPPING), &OVERLAPPING_LABELS);
    assert!(score < -0.05, "score was {}", score);
}

#[test]
fn separated_scores_above_overlapping() {
    let separated = dbcv(&to_array(&SEPARATED), &SEPARATED_LABELS);
    let overlapping = dbcv(&to_array(&OVERLAPPING), &OVERLAPPING_LABELS);
    assert!(separated > overlapping);
}

#[test]
fn a_single_cluster_is_unscoreable() {
    let labels = [0i32; 38];
    assert_eq!(dbcv(&to_array(&SEPARATED), &labels), -1.0);
}

#[test]
fn all_noise_is_unscoreable() {
    let labels = [-1i32; 38];
    assert_eq!(dbcv(&to_array(&SEPARATED), &labels), -1.0);
}
